COUNTS = {}


def it(groups, ch=None):
    """groups: [(見出し, [(項目, 定義・選択肢, 必須度, 根拠), ...])]。必須度は ◎/○/△（後ろに条件を付けてもよい）"""
    out = ['<table class="it fx"><thead><tr><th style="width:36mm">項目</th><th>定義・選択肢</th>'
           '<th style="width:12mm">必須度</th><th style="width:30mm">根拠</th></tr></thead><tbody>']
    for title, rows in groups:
        if title:
            out.append(f'<tr class="grp"><td colspan="4">{e(title)}</td></tr>')
        for a, b, lv, src in rows:
            cond = f'<div class="small">{e(lv[1:].strip("（）"))}</div>' if len(lv) > 1 else ''
            if ch:
                COUNTS.setdefault(ch, {'◎': 0, '○': 0, '△': 0})[lv[0]] += 1
            out.append(f'<tr><td><b>{e(a)}</b></td><td>{e(b)}</td><td class="lv">{LEV[lv[0]]}{cond}</td><td class="src">{e(src)}</td></tr>')
    out.append('</tbody></table>')
    return ''.join(out)


def T(h, rows, w=None):
    return table(h, rows, cls='fx', widths=w)


