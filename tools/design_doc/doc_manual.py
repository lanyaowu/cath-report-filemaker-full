def p_unused():
    out = ['<h1>6. 必要ない機能（不要・見直し候補）</h1>'
           '<p class="lead">現在の画面には、参考画面に合わせて作ったものの、まだ働かない機能や、同じ内容を何か所でも入力する項目があります。'
           '利用者の手間と入力ミスを減らすため、次の見直しを提案します。最終的な判断は運用担当の医師・管理者が行ってください。</p>' +
           table(['対応', '意味'], [
               ('非表示', '機能は残し、連携や様式ができるまで画面に出さない（設定で切替）'),
               ('統合', '入力欄を 1 か所にまとめ、他の場所は自動表示（参照のみ）にする'),
               ('読取専用', '過去データがあるときだけ表示し、新しい入力はさせない'),
               ('確認', '使い道を決めてから、残すか廃止するかを決める'),
               ('本番無効', 'デモ・開発のときだけ使い、本番の設定では使えなくする'),
           ], widths=['22mm', None])]
    for title, rows in UNUSED:
        out.append(f'<h2>{e(title)}</h2>')
        out.append(table(['優先', '機能・項目', '現状', '提案', '対応'],
                         [((PRI[p], 'c'), (e(a), 'k'), e(b), e(c), (e(d), 'c')) for p, a, b, c, d in rows],
                         cls='fx', widths=['11mm', '40mm', '50mm', None, '18mm'], raw=True))
    n = {k: sum(1 for _, rs in UNUSED for r in rs if r[4] == k) for k in ['非表示', '統合', '整理', '読取専用', '確認', '本番無効']}
    out.append('<h2>まとめ</h2>' + table(['対応', '件数'], [(k, (str(v), 'r')) for k, v in n.items() if v] +
                                       [(('合計', 'k'), (str(sum(n.values())), 'r k'))], widths=[None, '24mm']))
    return ''.join(out)


